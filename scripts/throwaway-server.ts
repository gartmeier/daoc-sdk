#!/usr/bin/env bun
// A disposable OpenDAoC stack for live checks that must leave the shared one
// (server/docker/docker-compose.yml) alone: its own compose project, volume and ports.
//
//   bun run server:throwaway up [--name=<name>] [--cold] [--timeout=<seconds>]
//   bun run server:throwaway down [--name=<name>]
//
// `up` exits 0 once a client can log in, and prints the ports it chose. Running it again
// on a stack that is up only prints them again. The name defaults to this checkout's
// folder, so each worktree gets its own stack; the generated compose file is in
// server/docker/throwaway/<name>/ (gitignored).
//
// The first `up` saves its freshly booted database in a seed volume outside every project,
// and later ones start from a copy: about 29 s instead of 66 s (docs/SERVER.md).

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { dbPinWarning, missingSubmodules } from './check-submodules';
import { botProperties, COMPOSE_FILE, probeGameServer, run, sql, sqlString, waitFor, type Ctx } from './setup-server';

const ROOT = join(import.meta.dir, '..');
const IMAGE = 'daoc-sdk-gameserver:latest';
const DB_INIT_TARGET = '/docker-entrypoint-initdb.d';
const PROJECT_PREFIX = 'daoc-throwaway-';
const SEED_PREFIX = 'daoc-seed-';
const MAX_SLOT = 9;

// ── Compose generation ──────────────────────────────────────────────────────

export interface Ports {
    game: number;
    udp: number;
    db: number;
}

/** Slot 0 is the shared stack. Slots end at 9, where the game ports would reach the UDP ones. */
export const slotPorts = (slot: number): Ports => ({ game: 10300 + 10 * slot, udp: 10400 + 10 * slot, db: 13306 + 10 * slot });

export function projectName(name: string): string {
    const slug = name.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^[-_]+|[-_]+$/g, '');
    if (!slug) throw new Error(`'${name}' has no letters or digits to name a stack with`);
    return PROJECT_PREFIX + slug;
}

export interface ComposeOptions {
    project: string;
    ports: Ports;
    /** Absolute path of server/db/opendaoc-db-core. */
    dbInitDir: string;
}

interface Service {
    image?: string;
    build?: unknown;
    restart?: string;
    ports?: string[];
    volumes?: (string | object)[];
    environment?: Record<string, string>;
    oom_score_adj?: number;
}

/**
 * The shared compose file with everything that could reach the shared stack replaced: the
 * project name (and with it the volume), the host ports, the relative mounts and the build.
 * A service this doesn't know about fails here rather than come up with the shared ports.
 */
export function generateCompose(source: string, { project, ports, dbInitDir }: ComposeOptions): string {
    const doc = Bun.YAML.parse(source) as { name?: string; services: Record<string, Service> };
    const { db, gameserver, ...others } = doc.services;
    if (!db || !gameserver) throw new Error('the compose file has no db or gameserver service');
    if (Object.keys(others).length) throw new Error(`the compose file has services this script doesn't know: ${Object.keys(others).join(', ')}`);
    doc.name = project;

    // A long-form mount: the colon after a Windows drive letter can't be misread.
    db.volumes = (db.volumes ?? []).map(v => typeof v === 'string' && v.includes(`:${DB_INIT_TARGET}`)
        ? { type: 'bind', source: dbInitDir, target: DB_INIT_TARGET, read_only: true }
        : v);
    db.ports = [`${ports.db}:3306`];

    delete gameserver.build;
    delete gameserver.volumes;   // the navmeshes: NPCs walk straight here, and it saves about 1.3 GB
    gameserver.image = IMAGE;
    gameserver.ports = [`${ports.game}:${ports.game}`, `${ports.udp}:${ports.udp}/udp`];
    // The server listens on, and tells clients, what the env says: a mapping alone isn't enough.
    gameserver.environment = {
        ...gameserver.environment,
        SERVER_PORT: String(ports.game),
        UDP_PORT: String(ports.udp),
        REGION_PORT: String(ports.udp),
    };

    for (const service of [db, gameserver]) {
        // A crash must fail `up`, not loop behind it, and a forgotten stack stays down after a Docker restart.
        service.restart = 'no';
        // If the Docker VM runs out of memory, this stack goes first instead of the shared gameserver, the largest process.
        service.oom_score_adj = 500;
    }

    return `# Generated by scripts/throwaway-server.ts from server/docker/docker-compose.yml.\n${Bun.YAML.stringify(doc, null, 2)}`;
}

/** The ports a generated compose file uses, so a second `up` keeps them. */
export function composePorts(text: string): Ports {
    const { services } = Bun.YAML.parse(text) as { services: Record<string, Service> };
    const env = services.gameserver?.environment;
    const ports = { game: Number(env?.SERVER_PORT), udp: Number(env?.UDP_PORT), db: Number(services.db?.ports?.[0]?.split(':')[0]) };
    if (!Object.values(ports).every(Number.isInteger)) throw new Error('not a generated compose file');
    return ports;
}

// ── Choosing ports ──────────────────────────────────────────────────────────

/** Host ports in `docker ps --format {{.Ports}}` output: `0.0.0.0:10320->10320/tcp, ...`. */
export function publishedPorts(ps: string): Set<number> {
    const found = new Set<number>();
    for (const m of ps.matchAll(/:(\d+)(?:-(\d+))?->/g)) {
        const first = Number(m[1]);
        for (let p = first; p <= Number(m[2] ?? first); p++) found.add(p);
    }
    return found;
}

/**
 * The first slot none of whose ports are published. It asks Docker, because on Windows a test
 * bind on a port Docker Desktop publishes succeeds. A slot another `up` takes meanwhile shows
 * up when the stack starts, and `up` then takes the next.
 */
export function firstFreeSlot(busy: Set<number>): Ports {
    for (let slot = 1; slot <= MAX_SLOT; slot++) {
        const ports = slotPorts(slot);
        if (!Object.values(ports).some(p => busy.has(p))) return ports;
    }
    throw new Error(`all ${MAX_SLOT} port slots are taken: see \`docker compose ls\``);
}

export const isPortConflict = (stderr: string) => /port is already allocated|address already in use|ports are not available/i.test(stderr);

// ── Readiness ───────────────────────────────────────────────────────────────

/** The line that means logins work. TCP answers through Docker's proxy long before it. */
export const listeningLine = (port: number) => `Server is now listening for incoming connections on 0.0.0.0:${port}`;

/** Why this image can't be trusted to hold the pinned code; null when it's newer than the pin. */
export function imagePinWarning(imageCreated: string, pinMoved: string): string | null {
    if (!(Date.parse(imageCreated) < Date.parse(pinMoved))) return null;
    return [
        `warning: ${IMAGE} was built ${imageCreated}, before server/core was last pinned (${pinMoved}), so it may lack that code`,
        'fix: docker compose -f server/docker/docker-compose.yml build gameserver   (a build only: the running shared stack stays as it is)',
    ].join('\n');
}

/** The account limits every bot trips over behind one Docker NAT address, with the values `server:setup` gives them. */
export const accountProperties = () => botProperties(1).filter(p => p.key === 'time_between_account_creation_sameip' || p.key === 'total_accounts_allowed_sameip');

// ── Seed volumes ────────────────────────────────────────────────────────────

/** Compose names a project's volume this way; a seed is copied into it before the first start. */
export const dataVolume = (project: string) => `${project}_db-data`;

/** Everything a freshly booted database comes out of. */
export interface SeedInputs {
    dumpCommit: string;
    /** `git status --porcelain` in server/db: an edited dump is another dump. */
    dumpChanges: string;
    gameImage: string;
    dbService: unknown;
    properties: [string, string][];
}

/** The seed for these inputs: anything that would change the database gets a seed of its own. */
export const seedVolumeName = (inputs: SeedInputs) => SEED_PREFIX + createHash('sha256').update(JSON.stringify(inputs)).digest('hex').slice(0, 12);

/** Seeds other than this one. Only exact seed names: nothing else on this Docker is ours to remove. */
export const staleSeeds = (volumes: string[], keep: string) => volumes.filter(v => v !== keep && new RegExp(`^${SEED_PREFIX}[0-9a-f]{12}$`).test(v));

// ── CLI ─────────────────────────────────────────────────────────────────────

export interface Options {
    command: 'up' | 'down';
    name: string;
    cold: boolean;
    timeoutMs: number;
}

export const USAGE = `usage: bun run server:throwaway <up|down> [options]
  --name=<name>        which stack (default: this checkout's folder name)
  --cold               seed from the dump and boot twice, neither using nor saving a seed volume
  --timeout=<seconds>  limit for each wait in \`up\` (default 600)`;

export function parseArgs(argv: string[], defaultName = basename(ROOT)): Options {
    const [command, ...rest] = argv;
    if (command !== 'up' && command !== 'down') throw new Error(USAGE);
    const opts: Options = { command, name: defaultName, cold: false, timeoutMs: 600_000 };
    for (const arg of rest) {
        const [flag, value] = arg.split(/=(.*)/s);
        if (arg === '--cold') opts.cold = true;
        else if (flag === '--name' && value) opts.name = value;
        else if (flag === '--timeout' && Number(value) > 0) opts.timeoutMs = Number(value) * 1000;
        else throw new Error(`unknown option '${arg}'\n${USAGE}`);
    }
    return opts;
}

interface Stack {
    project: string;
    file: string;
    ctx: Ctx;
}

function stackFor(name: string): Stack {
    const project = projectName(name);
    const file = join(ROOT, 'server', 'docker', 'throwaway', project.slice(PROJECT_PREFIX.length), 'docker-compose.yml');
    return { project, file, ctx: { compose: file, dbPassword: 'daoc-sdk', database: 'opendaoc', verbose: false } };
}

const compose = (stack: Stack, ...args: string[]) => run(['docker', 'compose', '-f', stack.file, ...args]);

const seconds = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

async function timed<T>(label: string, fn: () => Promise<T>): Promise<T> {
    const t0 = Date.now();
    const value = await fn();
    console.log(`  ${label}: ${seconds(Date.now() - t0)}`);
    return value;
}

/** Stops `up` before it builds on something that can't work, and says what to do about it. Returns the image's id. */
async function preflight(): Promise<string> {
    if (missingSubmodules(ROOT).includes('server/db'))
        throw new Error('server/db is empty, so there is no dump to seed from. run: git submodule update --init server/db');
    const dbWarning = dbPinWarning(ROOT);
    if (dbWarning) console.warn(dbWarning);

    const image = await run(['docker', 'image', 'inspect', IMAGE, '--format', '{{.Id}} {{.Created}}']);
    if (image.code !== 0) {
        throw new Error(`no ${IMAGE}: ${image.stderr.trim()}\n`
            + 'fix: docker compose -f server/docker/docker-compose.yml build gameserver   (needs server/core checked out)');
    }
    const pinMoved = await run(['git', '-C', ROOT, 'log', '-1', '--format=%cI', '--', 'server/core']);
    const [id, created] = image.stdout.trim().split(' ');
    const pinWarning = pinMoved.stdout.trim() ? imagePinWarning(created!, pinMoved.stdout.trim()) : null;
    if (pinWarning) console.warn(pinWarning);
    return id!;
}

async function choosePorts(): Promise<Ports> {
    const ps = await run(['docker', 'ps', '--format', '{{.Ports}}']);
    if (ps.code !== 0) throw new Error(`docker ps failed: ${ps.stderr.trim()}`);
    return firstFreeSlot(publishedPorts(ps.stdout));
}

function writeCompose(stack: Stack, ports: Ports): void {
    mkdirSync(dirname(stack.file), { recursive: true });
    writeFileSync(stack.file, generateCompose(readFileSync(COMPOSE_FILE, 'utf8'), {
        project: stack.project,
        ports,
        dbInitDir: join(ROOT, 'server', 'db', 'opendaoc-db-core'),
    }));
}

/** Starts the services, moving to the next free slot when a port turns out to be taken. Returns the ports in use. */
async function startServices(stack: Stack, ports: Ports, opts: Options): Promise<Ports> {
    for (let attempt = 0; ; attempt++) {
        const t0 = Date.now();
        const db = await compose(stack, 'up', '-d', '--wait', '--wait-timeout', String(Math.ceil(opts.timeoutMs / 1000)), 'db');
        const game = db.code === 0 ? await compose(stack, 'up', '-d', 'gameserver') : db;
        if (game.code === 0) {
            console.log(`  database healthy: ${seconds(Date.now() - t0)}`);
            return ports;
        }
        if (!isPortConflict(game.stderr) || attempt >= MAX_SLOT) throw new Error(`docker compose up failed: ${game.stderr.trim()}`);
        ports = await choosePorts();
        console.log(`  a port was taken, moving to ${ports.game}/${ports.udp}/${ports.db}`);
        writeCompose(stack, ports);
    }
}

/** Waits for this boot's listening line: the log keeps the line of the boot before a restart. */
async function waitUntilListening(stack: Stack, port: number, timeoutMs: number): Promise<void> {
    const line = listeningLine(port);
    const dead = await waitFor(`"${line}"`, timeoutMs, async () => {
        const id = (await compose(stack, 'ps', '-a', '-q', 'gameserver')).stdout.trim();
        if (!id) return undefined;
        const [status, startedAt] = (await run(['docker', 'inspect', id, '--format', '{{.State.Status}} {{.State.StartedAt}}'])).stdout.trim().split(' ');
        const logs = await run(['docker', 'logs', '--since', startedAt!, id]);
        if (status !== 'running') return `the gameserver is ${status}, last lines of its log:\n${logs.stdout.trim().split(/\r?\n/).slice(-20).join('\n')}`;
        return logs.stdout.includes(line) ? '' : undefined;
    });
    if (dead) throw new Error(dead);
}

/** The shared compose file's db service: part of what a seed depends on, and its image is at hand to copy volumes with. */
const sharedDbService = () => (Bun.YAML.parse(readFileSync(COMPOSE_FILE, 'utf8')) as { services: { db: { image: string } } }).services.db;

async function seedFor(gameImage: string): Promise<string> {
    const dump = join(ROOT, 'server', 'db');
    return seedVolumeName({
        dumpCommit: (await run(['git', '-C', dump, 'rev-parse', 'HEAD'])).stdout.trim(),
        dumpChanges: (await run(['git', '-C', dump, 'status', '--porcelain'])).stdout,
        gameImage,
        dbService: sharedDbService(),
        properties: accountProperties().map(p => [p.key, p.value]),
    });
}

/** A seed counts once its `data` folder is there: saveSeed renames it into place as its last step. */
const seedSaved = async (seed: string) =>
    (await run(['docker', 'run', '--rm', '-v', `${seed}:/seed:ro`, sharedDbService().image, 'test', '-d', '/seed/data'])).code === 0;

/** Fills the stack's volume before anything starts. Compose has to create it, or `down -v` leaves it behind as a stranger's. */
async function restoreSeed(stack: Stack, seed: string): Promise<void> {
    const created = await compose(stack, 'up', '--no-start');
    if (created.code !== 0) throw new Error(`docker compose up failed: ${created.stderr.trim()}`);
    const copied = await run(['docker', 'run', '--rm', '-v', `${seed}:/seed:ro`, '-v', `${dataVolume(stack.project)}:/data`,
        sharedDbService().image, 'cp', '-a', '/seed/data/.', '/data/']);
    if (copied.code !== 0) throw new Error(`restoring ${seed} failed: ${copied.stderr.trim()}`);
}

/**
 * Stops the stack, because only a stopped database copies whole, saves it and drops older
 * seeds, so a rebuilt image or a moved pin doesn't leave 400 MB behind each time. A seed
 * in use isn't removed, and failing to save one only costs the next `up` its speed.
 */
async function saveSeed(stack: Stack, seed: string): Promise<void> {
    const stopped = await compose(stack, 'stop');
    if (stopped.code !== 0) throw new Error(`docker compose stop failed: ${stopped.stderr.trim()}`);
    // The rename makes a seed whole or absent, and the first of two saving at once the one that stays.
    const save = 'tmp=/seed/.tmp-$(hostname) && mkdir "$tmp" && cp -a /data/. "$tmp"/ && { mv -T "$tmp" /seed/data 2>/dev/null || rm -rf "$tmp"; }';
    const saved = await run(['docker', 'run', '--rm', '-v', `${dataVolume(stack.project)}:/data:ro`, '-v', `${seed}:/seed`, sharedDbService().image, 'sh', '-c', save]);
    if (saved.code !== 0) console.warn(`warning: could not save ${seed}, so the next \`up\` starts cold too: ${saved.stderr.trim()}`);
    const volumes = await run(['docker', 'volume', 'ls', '-q', '--filter', `name=${SEED_PREFIX}`]);
    for (const stale of staleSeeds(volumes.stdout.split(/\r?\n/), seed)) await run(['docker', 'volume', 'rm', stale]);
}

/** Sets the account limits when they differ; the rows exist once the gameserver has booted. True when something changed. */
async function applyAccountProperties(ctx: Ctx): Promise<boolean> {
    const wanted = accountProperties();
    const keys = wanted.map(p => sqlString(p.key)).join(',');
    const rows = await waitFor('the serverproperty rows', 60_000, async () => {
        const found = await sql(ctx, `SELECT \`Key\`, Value FROM serverproperty WHERE \`Key\` IN (${keys});`);
        return found.length === wanted.length ? found : undefined;
    });
    const current = new Map(rows.map(([key, value]) => [key, value]));
    const stale = wanted.filter(p => current.get(p.key) !== p.value);
    if (!stale.length) return false;
    await sql(ctx, stale.map(p => `UPDATE serverproperty SET Value=${sqlString(p.value)}, LastTimeRowUpdated=NOW() WHERE \`Key\`=${sqlString(p.key)};`).join('\n'));
    return true;
}

async function up(opts: Options): Promise<void> {
    const t0 = Date.now();
    const gameImage = await preflight();
    const stack = stackFor(opts.name);
    const wanted = existsSync(stack.file) ? composePorts(readFileSync(stack.file, 'utf8')) : await choosePorts();
    writeCompose(stack, wanted);
    console.log(`stack ${stack.project}, ports ${wanted.game}/${wanted.udp}/${wanted.db}:`);
    const downCommand = `bun run server:throwaway down${opts.name === basename(ROOT) ? '' : ` --name=${opts.name}`}`;

    try {
        const seed = opts.cold ? null : await seedFor(gameImage);
        // Only into a stack that has no database yet: one that exists keeps its data.
        const fresh = (await run(['docker', 'volume', 'inspect', dataVolume(stack.project)])).code !== 0;
        if (seed && fresh && await seedSaved(seed)) await timed('seed restored', () => restoreSeed(stack, seed));

        let ports = await startServices(stack, wanted, opts);
        await timed('gameserver listening', () => waitUntilListening(stack, ports.game, opts.timeoutMs));
        if (await timed('account limits checked', () => applyAccountProperties(stack.ctx))) {
            if (seed && !(await seedSaved(seed))) {
                await timed('seed saved', () => saveSeed(stack, seed));
                ports = await startServices(stack, ports, opts);
            } else {
                await timed('gameserver restarted', async () => {
                    const r = await compose(stack, 'restart', 'gameserver');
                    if (r.code !== 0) throw new Error(`docker compose restart failed: ${r.stderr.trim()}`);
                });
            }
            await timed('gameserver listening again', () => waitUntilListening(stack, ports.game, opts.timeoutMs));
        }
        // Docker Desktop publishes a port on top of a listener outside Docker without a word, and that listener gets the connections.
        await waitFor(`the handshake on 127.0.0.1:${ports.game}`, 30_000, async () => ((await probeGameServer('127.0.0.1', ports.game)) ? true : undefined))
            .catch((e: Error) => { throw new Error(`${e.message}. The server inside is listening, so another program may hold that port on this machine`); });

        console.log(`ready in ${seconds(Date.now() - t0)}
  game  127.0.0.1:${ports.game}   SERVER=127.0.0.1:${ports.game} in bot.env, or host and port for a DaocClient
  udp   127.0.0.1:${ports.udp}
  db    127.0.0.1:${ports.db}   root / ${stack.ctx.dbPassword}, database ${stack.ctx.database}
  file  ${stack.file}
  down  ${downCommand}`);
    } catch (e) {
        console.error(`the stack is left for a look: docker compose -f ${stack.file} logs\nremove it with: ${downCommand}`);
        throw e;
    }
}

async function down(opts: Options): Promise<void> {
    const stack = stackFor(opts.name);
    // Without the file (a checkout cleaned since) the project name still reaches this stack and no other.
    const r = existsSync(stack.file)
        ? await compose(stack, 'down', '-v')
        : await run(['docker', 'compose', '-p', stack.project, 'down', '-v']);
    if (r.code !== 0) throw new Error(`docker compose down failed: ${r.stderr.trim()}`);
    rmSync(dirname(stack.file), { recursive: true, force: true });
    console.log(`stack ${stack.project} and its volume are gone`);
}

if (import.meta.main) {
    try {
        const opts = parseArgs(process.argv.slice(2));
        await (opts.command === 'up' ? up(opts) : down(opts));
    } catch (e) {
        console.error(`throwaway-server: ${e instanceof Error ? e.message : String(e)}`);
        process.exit(1);
    }
}
